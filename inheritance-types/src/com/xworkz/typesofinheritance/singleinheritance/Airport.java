package com.xworkz.typesofinheritance.singleinheritance;

public class Airport {

    public void airportName() {
        System.out.println("Kempegowda International Airport");
    }

    public void location() {
        System.out.println("Bangalore, Karnataka");
    }

    public void terminalCount() {
        System.out.println("2");
    }

    public void runwayLength() {
        System.out.println("4000 meters");
    }

    public void openedYear() {
        System.out.println("2008");
    }

    public void airportCode() {
        System.out.println("BLR");
    }

    public void totalFlightsDaily() {
        System.out.println("600+ flights");
    }

    public void cargoFacility() {
        System.out.println("Available");
    }
}
