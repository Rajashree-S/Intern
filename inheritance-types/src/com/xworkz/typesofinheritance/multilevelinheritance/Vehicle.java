package com.xworkz.typesofinheritance.multilevelinheritance;

public class Vehicle {

    public void vehicleType() {
        System.out.println("Public Transport");
    }

    public void brand() {
        System.out.println("Tata Motors");
    }

    public void fuelType() {
        System.out.println("Diesel");
    }

    public void color() {
        System.out.println("White");
    }

    public void capacity() {
        System.out.println("50 seats");
    }

    public void wheelCount() {
        System.out.println("6 wheels");
    }

    public void registrationNumber() {
        System.out.println("KA-05-1234");
    }

    public void vehicleWeight() {
        System.out.println("8500 kg");
    }
}
