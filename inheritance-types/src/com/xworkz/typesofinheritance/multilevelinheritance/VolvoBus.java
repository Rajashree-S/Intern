package com.xworkz.typesofinheritance.multilevelinheritance;

public class VolvoBus extends Bus{

    public void acAvailable() {
        System.out.println("Yes");
    }

    public void usbCharging() {
        System.out.println("Available at every seat");
    }

    public void wifiAvailable() {
        System.out.println("high-speed Wi-Fi");
    }

    public void reclinerSeats() {
        System.out.println("Fully Reclining");
    }

    public void entertainmentSystem() {
        System.out.println("Individual screens with movies");
    }

    public void safetyFeatures() {
        System.out.println("Airbags and ABS");
    }

    public void driverName() {
        System.out.println("Hamith");
    }

    public void travelAgency() {
        System.out.println("vvv Travels");
    }
}
