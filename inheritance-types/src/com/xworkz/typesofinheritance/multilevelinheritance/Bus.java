package com.xworkz.typesofinheritance.multilevelinheritance;

public class Bus extends Vehicle{

    public void busNumber() {
        System.out.println("KSRTC 403B");
    }

    public void routeName() {
        System.out.println("Bangalore to Mysore");
    }

    public void busType() {
        System.out.println("Express");
    }

    public void conductorName() {
        System.out.println("Ramesh");
    }

    public void ticketPrice() {
        System.out.println("150rs");
    }

    public void stopCount() {
        System.out.println("12 stops");
    }

    public void boardingTime() {
        System.out.println("06:30 AM");
    }

    public void reachingTime() {
        System.out.println("10:15 AM");
    }
}
