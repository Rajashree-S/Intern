package com.xworkz.typesofinheritance.hybridinheritance;

public class UserLogin extends StreamingPlatform{

    public void userName() {
        System.out.println("john doe");
    }

    public void password() {
        System.out.println("john@123");
    }

    public void loginStatus() {
        System.out.println("Login Successful");
    }

    public void accountType() {
        System.out.println("Personal Account");
    }

    public void emailId() {
        System.out.println("john@example.com");
    }

    public void mobileNumber() {
        System.out.println("9876543210");
    }

    public void lastLogin() {
        System.out.println("16-04-2025 10:45 AM");
    }

    public void membershipValidity() {
        System.out.println("Valid till: 16-10-2025");
    }
}
